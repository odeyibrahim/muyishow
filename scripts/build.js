#!/usr/bin/env node
/* Netlify build step. Reads the latest content from Supabase (if configured), bakes it into index.html so the site
   works with no JavaScript and is fast for search engines, and writes the public Supabase settings for the browser. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), site = path.join(root, 'site');
const R = require(path.join(site, 'assets/js/render.js'));
const DEF = require(path.join(site, 'assets/js/content.default.js'));
const URL_ = (process.env.SUPABASE_URL || '').replace(/\/$/, ''), KEY = process.env.SUPABASE_ANON_KEY || '';

async function main() {
  let c = JSON.parse(JSON.stringify(DEF));
  if (URL_ && KEY) {
    try {
      const r = await fetch(URL_ + '/rest/v1/site_content?select=key,value', { headers: { apikey: KEY, Authorization: 'Bearer ' + KEY } });
      if (!r.ok) throw new Error('HTTP ' + r.status);
      const rows = await r.json();
      rows.forEach(x => { if (x && x.key && x.value != null) c[x.key] = x.value; });
      console.log('[build] merged ' + rows.length + ' saved section(s) from Supabase');
    } catch (e) { console.warn('[build] could not read Supabase (' + e.message + '). Using built-in content.'); }
  } else console.log('[build] SUPABASE_URL / SUPABASE_ANON_KEY not set: using built-in content.');
  c._built = new Date().toISOString();

  fs.writeFileSync(path.join(site, 'assets/js/config.js'),
    '/* Generated by scripts/build.js. The anon key is public by design; row-level security protects the data. */\n' +
    'window.MSCO_CONFIG = ' + JSON.stringify({ supabaseUrl: URL_, supabaseAnonKey: KEY }) + ';\n');

  const s = c.site || {}, origin = (process.env.URL && !/localhost/.test(process.env.URL) ? s.origin || process.env.URL : s.origin || '').replace(/\/$/, '');
  const e = R.esc;
  const html = fs.readFileSync(path.join(__dirname, 'template.html'), 'utf8')
    .replace(/{{TITLE}}/g, () => e(s.title)).replace(/{{DESC}}/g, () => e(s.description)).replace(/{{CANON}}/g, () => e(origin))
    .replace('{{FONT_HREF}}', () => e(R.fontHref(c.theme))).replace('{{FONT_CSS}}', () => R.fontCss(c.theme))
    .replace('{{JSONLD}}', () => R.jsonld(c)).replace('{{APP}}', () => R.page(c))
    .replace('{{CONTENT}}', () => JSON.stringify(c).replace(/</g, '\\u003c').replace(/\u2028|\u2029/g, ''));
  fs.writeFileSync(path.join(site, 'index.html'), html);
  fs.writeFileSync(path.join(site, 'robots.txt'), 'User-agent: *\nDisallow: /admin/\n' + (origin ? 'Sitemap: ' + origin + '/sitemap.xml\n' : ''));
  if (origin) fs.writeFileSync(path.join(site, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>' + origin + '/</loc></url></urlset>\n');
  console.log('[build] wrote site/index.html (' + Math.round(html.length / 1024) + ' KB)');
}
main().catch(e => { console.error(e); process.exit(1); });

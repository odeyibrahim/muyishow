#!/usr/bin/env node
/**
 * Build step (run by Netlify on every deploy).
 *
 *  1. Reads the latest content from Supabase when SUPABASE_URL and SUPABASE_ANON_KEY are set,
 *     otherwise uses the built-in content in site/assets/js/content.default.js.
 *  2. Renders site/index.html so the page is complete before any JavaScript runs
 *     (faster first paint, and fully readable by search engines).
 *  3. Writes assets/js/config.js (public Supabase settings), robots.txt, sitemap.xml and site.webmanifest.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const site = path.join(root, 'site');
const R = require(path.join(site, 'assets/js/render.js'));
const DEFAULTS = require(path.join(site, 'assets/js/content.default.js'));

const SUPABASE_URL = (process.env.SUPABASE_URL || '').replace(/\/$/, '');
const SUPABASE_ANON_KEY = process.env.SUPABASE_ANON_KEY || '';

const write = (file, text) => fs.writeFileSync(path.join(site, file), text);

async function loadContent() {
  const content = JSON.parse(JSON.stringify(DEFAULTS));
  if (!SUPABASE_URL || !SUPABASE_ANON_KEY) {
    console.log('[build] Supabase not configured: using built-in content.');
    return content;
  }
  try {
    const res = await fetch(`${SUPABASE_URL}/rest/v1/site_content?select=key,value`, {
      headers: { apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` }
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const rows = await res.json();
    rows.forEach((row) => { if (row && row.key && row.value != null) content[row.key] = row.value; });
    console.log(`[build] Merged ${rows.length} saved section(s) from Supabase.`);
  } catch (err) {
    console.warn(`[build] Could not read Supabase (${err.message}); using built-in content.`);
  }
  return content;
}

async function main() {
  const c = await loadContent();
  const builtAt = new Date();
  c._built = builtAt.toISOString();
  const s = c.site || {};
  const origin = String(s.origin || process.env.URL || '').replace(/\/$/, '');
  const e = R.esc;

  write('assets/js/config.js',
    '/* Generated by scripts/build.js. The anon key is public by design; row-level security protects the data. */\n' +
    `window.MSCO_CONFIG = ${JSON.stringify({ supabaseUrl: SUPABASE_URL, supabaseAnonKey: SUPABASE_ANON_KEY })};\n`);

  const html = fs.readFileSync(path.join(__dirname, 'template.html'), 'utf8')
    .replace(/{{TITLE}}/g, () => e(s.title))
    .replace(/{{DESC}}/g, () => e(s.description))
    .replace(/{{NAME}}/g, () => e(s.name))
    .replace(/{{CANON}}/g, () => e(origin))
    .replace('{{FONT_HREF}}', () => e(R.fontHref(c.theme)))
    .replace('{{FONT_CSS}}', () => R.fontCss(c.theme))
    .replace('{{JSONLD}}', () => R.jsonld(c, origin))
    .replace('{{APP}}', () => R.page(c))
    .replace('{{CONTENT}}', () => JSON.stringify(c).replace(/</g, '\\u003c').replace(/\u2028|\u2029/g, ''));
  write('index.html', html);

  write('robots.txt', `User-agent: *\nAllow: /\nDisallow: /admin/\n${origin ? `\nSitemap: ${origin}/sitemap.xml\n` : ''}`);
  if (origin) {
    write('sitemap.xml',
      '<?xml version="1.0" encoding="UTF-8"?>\n' +
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
      `  <url>\n    <loc>${e(origin)}/</loc>\n    <lastmod>${builtAt.toISOString().slice(0, 10)}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>1.0</priority>\n  </url>\n` +
      '</urlset>\n');
  }
  write('site.webmanifest', JSON.stringify({
    name: s.name, short_name: 'Muyi Sowemimo', description: s.description, lang: 'en-NG', start_url: '/', scope: '/', display: 'browser',
    background_color: '#3a0b14', theme_color: '#3a0b14',
    icons: [
      { src: 'assets/img/icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: 'assets/img/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' }
    ]
  }, null, 2) + '\n');

  console.log(`[build] Wrote site/index.html (${Math.round(html.length / 1024)} KB).`);
}

main().catch((err) => { console.error(err); process.exit(1); });
